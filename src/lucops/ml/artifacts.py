"""Persistence for trusted local LucOps models only.

Joblib can execute code during loading. Metadata and checksums detect mistakes,
not malicious artifacts. Never pass models or metadata from unknown sources.
"""

import hashlib
import io
import json
from pathlib import Path

import joblib
import sklearn
from sklearn.ensemble import IsolationForest
from sklearn.utils.validation import check_is_fitted


def _validate_metadata(metadata: object) -> None:
    if not isinstance(metadata, dict):
        raise ValueError("Invalid model metadata: expected a JSON object.")  # noqa: TRY004 - invalid artifact data
    expected = {
        "artifact_format": 1,
        "producer": "lucops-ai",
        "algorithm": "IsolationForest",
        "features": ["valor"],
        "sklearn_version": sklearn.__version__,
    }
    for field, value in expected.items():
        if metadata.get(field) != value:
            raise ValueError(f"Incompatible model metadata: {field}.")
    version = metadata.get("model_version")
    count = metadata.get("training_records")
    checksum = metadata.get("sha256")
    if not isinstance(version, str) or not version.strip():
        raise ValueError("Invalid model metadata: model_version.")
    if type(count) is not int or count < 2:
        raise ValueError("Invalid model metadata: training_records.")
    if not isinstance(metadata.get("training_parameters"), dict):
        raise ValueError("Invalid model metadata: training_parameters.")  # noqa: TRY004 - invalid artifact data
    if (
        not isinstance(checksum, str)
        or len(checksum) != 64
        or any(char not in "0123456789abcdef" for char in checksum)
    ):
        raise ValueError("Invalid model metadata: sha256.")


def _validate_model(model: object) -> None:
    if type(model) is not IsolationForest:
        raise ValueError("Incompatible model: expected IsolationForest.")
    check_is_fitted(model)
    if model.n_features_in_ != 1:
        raise ValueError("Incompatible model: expected the single attribute valor.")
    count = getattr(model, "training_record_count_", None)
    if type(count) is not int or count < 2:
        raise ValueError("Model must be trained by lucops.ml.training.train_detector.")


def save_model(
    model: IsolationForest,
    file_path: str | Path,
    *,
    model_version: str = "iforest-v1",
) -> dict:
    """Save a trained project model and JSON sidecar; refuse overwrites."""
    _validate_model(model)
    path = Path(file_path)
    metadata_path = Path(str(path) + ".json")
    buffer = io.BytesIO()
    joblib.dump(model, buffer)
    payload = buffer.getvalue()
    metadata = {
        "artifact_format": 1,
        "producer": "lucops-ai",
        "algorithm": "IsolationForest",
        "model_version": model_version,
        "features": ["valor"],
        "training_parameters": model.get_params(deep=False),
        "sklearn_version": sklearn.__version__,
        "training_records": model.training_record_count_,
        "sha256": hashlib.sha256(payload).hexdigest(),
    }
    _validate_metadata(metadata)
    serialized = json.dumps(metadata, indent=2, allow_nan=False)
    if path.exists() or metadata_path.exists():
        raise FileExistsError(f"Model or metadata already exists: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("xb") as destination:
        destination.write(payload)
    with metadata_path.open("x", encoding="utf-8") as destination:
        destination.write(serialized + "\n")
    return metadata


def load_model(file_path: str | Path) -> tuple[IsolationForest, dict]:
    """Load ONLY trusted local artifacts generated by save_model.

    Requires the exact training Scikit-learn version and matching metadata.
    A checksum is an integrity check, not proof that a model is trustworthy.
    """
    path = Path(file_path)
    metadata_path = Path(str(path) + ".json")
    for required in (path, metadata_path):
        if not required.is_file():
            raise FileNotFoundError(f"Model artifact file not found: {required}")
    try:
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    except (ValueError, UnicodeError) as exc:
        raise ValueError(f"Corrupted model metadata: {metadata_path}") from exc
    _validate_metadata(metadata)
    payload = path.read_bytes()
    if hashlib.sha256(payload).hexdigest() != metadata["sha256"]:
        raise ValueError(f"Corrupted model: checksum mismatch for {path}")
    try:
        model = joblib.load(io.BytesIO(payload))
        _validate_model(model)
        if (
            model.get_params(deep=False) != metadata["training_parameters"]
            or model.training_record_count_ != metadata["training_records"]
        ):
            raise ValueError("Model does not match its metadata.")
    except Exception as exc:
        raise ValueError(f"Corrupted or incompatible model: {exc}") from exc
    return model, metadata
