"""Independent ML commands; the main LucOps CLI is unchanged."""

import argparse
import json
from dataclasses import asdict
from pathlib import Path

from .artifacts import load_model, save_model
from .detector import analyze_transactions
from .features import prepare_csv_features
from .training import train_detector


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        description="LucOps ML: train and analyze with trusted local artifacts only."
    )
    commands = parser.add_subparsers(dest="command", required=True)
    train = commands.add_parser("train", help="Train and save a new local model.")
    train.add_argument("csv_file", type=Path)
    train.add_argument("--model", type=Path, required=True)
    train.add_argument("--model-version", default="iforest-v1")
    analyze = commands.add_parser("analyze", help="Analyze without training.")
    analyze.add_argument("csv_file", type=Path)
    analyze.add_argument(
        "--model",
        type=Path,
        required=True,
        help="Trusted local model generated by this project's train command only.",
    )
    analyze.add_argument("--output", type=Path, help="Save JSON; must not exist.")
    args = parser.parse_args(argv)

    try:
        if args.command == "train":
            if args.csv_file.resolve() in {
                args.model.resolve(),
                Path(str(args.model) + ".json").resolve(),
            }:
                raise ValueError("Model paths must differ from the input CSV.")
            data = prepare_csv_features(args.csv_file)
            model = train_detector(data)
            metadata = save_model(model, args.model, model_version=args.model_version)
            payload = {
                "model_path": str(args.model),
                "metadata": metadata,
                "skipped_records": len(data.ineligible),
                "ineligible": [asdict(record) for record in data.ineligible],
            }
        else:
            model, metadata = load_model(args.model)
            data = prepare_csv_features(args.csv_file)
            result = analyze_transactions(model, data)
            payload = {
                "model_version": metadata["model_version"],
                "evaluated_records": len(result.results),
                "skipped_records": len(result.ineligible),
                "anomalies_detected": sum(r.is_anomaly for r in result.results),
                **asdict(result),
            }
        output = json.dumps(payload, ensure_ascii=True, indent=2, allow_nan=False)
        if args.command == "analyze" and args.output is not None:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            with args.output.open("x", encoding="utf-8") as destination:
                destination.write(output + "\n")
        print(output)
    except (OSError, ValueError) as exc:
        parser.error(str(exc))


if __name__ == "__main__":
    main()
